interface LanguageContextType {
  currentLanguage: LanguageOption;
  setLanguageCode: (code: string) => void;
  isRTL: boolean;
  t: (key: string, fallback?: string) => string;
}

const LanguageContext = createContext<LanguageContextType>({
  currentLanguage: INDIAN_LANGUAGES[0],
  setLanguageCode: () => {},
  isRTL: false,
  t: (key, fallback) => fallback || key,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [currentLangCode, setCurrentLangCode] = useState<string>("en");

  useEffect(() => {
    const saved = localStorage.getItem("careflow_lang");
    if (saved && INDIAN_LANGUAGES.some((l) => l.code === saved)) {
      setCurrentLangCode(saved);
    }
  }, []);

  const setLanguageCode = (code: string) => {
    setCurrentLangCode(code);
    localStorage.setItem("careflow_lang", code);
  };

  const currentLanguage =
    INDIAN_LANGUAGES.find((l) => l.code === currentLangCode) || INDIAN_LANGUAGES[0];
  const isRTL = Boolean(currentLanguage.isRTL);

  useEffect(() => {
    document.documentElement.dir = isRTL ? "rtl" : "ltr";
    document.documentElement.lang = currentLanguage.code;
    document.body.setAttribute("data-lang", currentLanguage.code);
  }, [isRTL, currentLanguage.code]);

  const t = (key: string, fallback?: string): string => {
    const langDict = TRANSLATIONS[currentLanguage.code] || TRANSLATIONS["en"];
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    if (TRANSLATIONS["en"] && TRANSLATIONS["en"][key]) {
      return TRANSLATIONS["en"][key];
    }
    return fallback || key;
  };

  return (
    <LanguageContext.Provider value={{ currentLanguage, setLanguageCode, isRTL, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
